let displayNames: Intl.DisplayNames | null = null
try {
  displayNames = new Intl.DisplayNames(['en'], { type: 'region' })
} catch {
  displayNames = null
}

export function countryName(code: string): string {
  try {
    return displayNames?.of(code) ?? code
  } catch {
    return code
  }
}

/** "India (IN)" */
export function countryLabel(code: string): string {
  const name = countryName(code)
  return name === code ? code : `${name} (${code})`
}

/**
 * Countries whose name or code matches query (case-insensitive): an exact
 * code first, then names starting with the query, then other name matches.
 */
export function searchCountries(query: string, exclude: Iterable<string> = []): string[] {
  const q = query.trim().toLowerCase()
  const skip = new Set(exclude)
  const rank = (c: string): number => {
    const name = countryName(c).toLowerCase()
    if (c.toLowerCase() === q) return 0
    if (name.startsWith(q)) return 1
    return 2
  }
  return COUNTRY_CODES.filter((c) => !skip.has(c))
    .filter((c) => !q || c.toLowerCase() === q || countryName(c).toLowerCase().includes(q))
    .sort((a, b) => rank(a) - rank(b) || countryName(a).localeCompare(countryName(b)))
}

