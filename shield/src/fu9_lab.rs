//! FU-9 lab harness, Shield side (PENDING-21 §11). Not a unit test: run by
//! hand in its own network namespace, against the Connector side
//! (`connector/src/fu9_lab.rs`) behind an emulated link. Production code on
//! this side: the mTLS channel to the Connector (`tls::build_connector_channel`
//! with the FU-9 HTTP/2 settings) and the tunnel module (`tunnel::*`). The
//! Control loop is a reduced copy of `control_stream.rs`: it opens and aborts
//! tunnels, acks the harness commands, and performs the renewal handover
//! (new certificate, new connection, old Control half-closed and drained).
//!
//! ```text
//! LAB_DIR=/tmp/lab LAB_CONNECTOR=10.9.0.1:9091 \
//!   cargo test --release fu9_lab -- --ignored --nocapture
//! ```

use std::time::{Duration, Instant};

use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::{TcpListener, UdpSocket};
use tokio::sync::mpsc;
use tokio_stream::wrappers::ReceiverStream;

use crate::proto::shield_control_message::Body;
use crate::proto::shield_service_client::ShieldServiceClient;
use crate::proto::{ResourceAck, ShieldControlMessage, ShieldHealthReport};
use crate::tunnel::{self, TunnelHub};

const TCP_RESOURCE: u16 = 18080;
const UDP_RESOURCE: u16 = 18081;

/// Must match `connector/src/fu9_lab.rs`.
fn gen_byte(i: u64) -> u8 {
    ((i as u32).wrapping_mul(2_654_435_761).rotate_left(7) >> 3) as u8
}

fn log(t0: Instant, msg: impl AsRef<str>) {
    println!("[{:7.2}s] shield: {}", t0.elapsed().as_secs_f64(), msg.as_ref());
}

/// The download resource: reads "N\n", sends N generated bytes, closes.
async fn tcp_resource(t0: Instant) {
    let l = TcpListener::bind(("127.0.0.1", TCP_RESOURCE)).await.unwrap();
    loop {
        let (mut s, _) = l.accept().await.unwrap();
        tokio::spawn(async move {
            let mut line = Vec::new();
            let mut b = [0u8; 1];
            while s.read_exact(&mut b).await.is_ok() && b[0] != b'\n' {
                line.push(b[0]);
            }
            let size: u64 = String::from_utf8_lossy(&line).parse().unwrap_or(0);
            let mut buf = vec![0u8; 16 * 1024];
            let mut i = 0u64;
            while i < size {
                let n = (size - i).min(buf.len() as u64) as usize;
                for (k, x) in buf[..n].iter_mut().enumerate() {
                    *x = gen_byte(i + k as u64);
                }
                if let Err(e) = s.write_all(&buf[..n]).await {
                    log(t0, format!("resource: download of {size} ended at {i} bytes: {e}"));
                    return;
                }
                i += n as u64;
            }
            let _ = s.shutdown().await;
        });
    }
}

/// The UDP resource: "go" → 5000 numbered 1 KB datagrams at once;
/// "ping" → "pong".
async fn udp_resource() {
    let s = UdpSocket::bind(("127.0.0.1", UDP_RESOURCE)).await.unwrap();
    let mut buf = [0u8; 2048];
    loop {
        let (n, peer) = s.recv_from(&mut buf).await.unwrap();
        match &buf[..n] {
            b"go" => {
                for i in 0u32..5000 {
                    let mut d = vec![0u8; 1024];
                    d[..4].copy_from_slice(&i.to_be_bytes());
                    let _ = s.send_to(&d, peer).await;
                }
            }
            b"ping" => {
                let _ = s.send_to(b"pong", peer).await;
            }
            _ => {}
        }
    }
}

struct Lab {
    dir: String,
    addr: String,
    connector_id: String,
    trust_domain: String,
}

impl Lab {
    async fn client(&self, which: &str) -> ShieldServiceClient<tonic::transport::Channel> {
        let read = |n: &str| std::fs::read(format!("{}/{n}", self.dir)).unwrap();
        let channel = crate::tls::build_connector_channel(
            &read("ca.pem"),
            &read(&format!("shield-{which}.crt")),
            &read(&format!("shield-{which}.key")),
            &self.connector_id,
            &self.trust_domain,
            &self.addr,
        )
        .await
        .unwrap();
        ShieldServiceClient::new(channel)
    }
}

fn health() -> ShieldControlMessage {
    ShieldControlMessage {
        body: Some(Body::HealthReport(ShieldHealthReport {
            version: "fu9-lab".into(),
            hostname: "lab-shield".into(),
            public_ip: String::new(),
            lan_ip: "127.0.0.1".into(),
        })),
    }
}

fn established_to_connector(addr: &str) -> String {
    let port = addr.rsplit_once(':').unwrap().1;
    let out = std::process::Command::new("ss")
        .args(["-Htn", "state", "established", &format!("( dport = :{port} )")])
        .output()
        .unwrap();
    let ports: Vec<String> = String::from_utf8_lossy(&out.stdout)
        .lines()
        .filter_map(|l| l.split_whitespace().nth(2).map(|a| a.rsplit_once(':').unwrap().1.to_string()))
        .collect();
    format!("{} connection(s) {:?}", ports.len(), ports)
}

/// What a Control message asks of the harness.
enum Next {
    Continue,
    Renew,
}

async fn handle(
    t0: Instant,
    msg: ShieldControlMessage,
    hub: &TunnelHub,
    out: &mpsc::Sender<ShieldControlMessage>,
) -> Next {
    match msg.body {
        Some(Body::TunnelOpen(open)) => tunnel::handle_tunnel_open(hub.clone(), open).await,
        Some(Body::TunnelClose(close)) => tunnel::abort_tunnel(hub, &close.connection_id),
        Some(Body::ResourceInstruction(cmd)) => {
            let _ = out
                .send(ShieldControlMessage {
                    body: Some(Body::ResourceAck(ResourceAck {
                        resource_id: cmd.resource_id.clone(),
                        status: "protected".into(),
                        ..Default::default()
                    })),
                })
                .await;
            if cmd.resource_id == "renew" {
                log(t0, "renew requested");
                return Next::Renew;
            }
        }
        _ => {}
    }
    Next::Continue
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "FU-9 lab harness: run by hand in the netns lab (PENDING-21 §11)"]
async fn fu9_lab_shield() {
    let _ = rustls::crypto::ring::default_provider().install_default();
    let dir = std::env::var("LAB_DIR").expect("LAB_DIR");
    let addr = std::env::var("LAB_CONNECTOR").expect("LAB_CONNECTOR");
    let t0 = Instant::now();
    while !std::path::Path::new(&format!("{dir}/ready")).exists() {
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    let ids = std::fs::read_to_string(format!("{dir}/ids")).unwrap();
    let mut ids = ids.lines();
    let lab = Lab {
        dir: dir.clone(),
        addr: addr.clone(),
        connector_id: ids.next().unwrap().to_string(),
        trust_domain: ids.next().unwrap().to_string(),
    };
    tokio::spawn(tcp_resource(t0));
    tokio::spawn(udp_resource());

    let hub = tunnel::new_hub();
    let mut client = lab.client("a").await;
    let (mut out, rx) = mpsc::channel(32);
    let mut inbound = client.control(ReceiverStream::new(rx)).await.unwrap().into_inner();
    hub.set_client(Some(client.clone()));
    hub.set_upstream(Some(out.clone()));
    out.send(health()).await.unwrap();
    log(t0, format!("attached with certificate A; {}", established_to_connector(&addr)));
    let mut health_tick = tokio::time::interval(Duration::from_secs(5));
    let mut ss_tick = tokio::time::interval(Duration::from_secs(5));

    loop {
        tokio::select! {
            _ = health_tick.tick() => { let _ = out.send(health()).await; }
            _ = ss_tick.tick() => {
                log(t0, format!("tunnels {}; {}", hub.len(), established_to_connector(&addr)));
            }
            msg = inbound.message() => match msg {
                Ok(Some(msg)) => {
                    if let Next::Renew = handle(t0, msg, &hub, &out).await {
                        // Renewal handover, as control_stream::hand_over.
                        let mut new_client = lab.client("b").await;
                        let (new_out, new_rx) = mpsc::channel(32);
                        let new_inbound = new_client
                            .control(ReceiverStream::new(new_rx))
                            .await
                            .unwrap()
                            .into_inner();
                        hub.set_upstream(None);
                        hub.set_client(Some(new_client.clone()));
                        drop(std::mem::replace(&mut out, new_out));
                        let mut old_inbound = std::mem::replace(&mut inbound, new_inbound);
                        let old_client = std::mem::replace(&mut client, new_client);
                        while let Ok(Some(m)) = old_inbound.message().await {
                            handle(t0, m, &hub, &out).await;
                        }
                        drop(old_client);
                        hub.set_upstream(Some(out.clone()));
                        let _ = out.send(health()).await;
                        log(t0, format!(
                            "renewed: on certificate B; tunnels {}; {}",
                            hub.len(),
                            established_to_connector(&addr)
                        ));
                    }
                }
                Ok(None) | Err(_) => {
                    log(t0, format!("control stream ended ({msg:?}); closing {} tunnels", hub.close_all()));
                    break;
                }
            },
        }
    }
    tokio::time::sleep(Duration::from_secs(3)).await;
    log(t0, format!("end: tunnels {}; {}", hub.len(), established_to_connector(&addr)));
}
